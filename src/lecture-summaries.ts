export type LectureSection = {
  title: string;
  paragraphs: string[];
  formula: string;
  example: string;
  code: string;
  checks?: { question: string; answer: string }[];
};

export type LectureSummary = {
  id: string;
  scopes: string[];
  title: string;
  sources: string[];
  location: string;
  recordingStatus: string;
  overview: string;
  sections: LectureSection[];
};

export function getLectureSearchText(lecture: LectureSummary): string {
  return [lecture.title, lecture.overview, lecture.location, lecture.recordingStatus, ...lecture.sources,
    ...lecture.sections.flatMap((section) => [section.title, ...section.paragraphs, section.formula, section.example, section.code,
      ...(section.checks ?? []).flatMap((check) => [check.question, check.answer])])].join(' ').toLocaleLowerCase();
}

export function findLectureSummaries(scope: string, query = ''): LectureSummary[] {
  const terms = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  return lectureSummaries.filter((lecture) => (scope === 'all' || lecture.scopes.includes(scope))
    && terms.every((term) => getLectureSearchText(lecture).includes(term)));
}

